//! `index.tsv`, `graph.json` and the tree's own README.
//!
//! All three are rebuilt from **every** file in the tree, never from just the
//! functions the current run walked. Without that, a targeted top-up
//! (`--anchor` / `--anchors-file`, which is the common case once the tree
//! exists) would overwrite an index of 1500 functions with its own handful and
//! lose the rest. It also makes `--anchor <anything> --depth 0` a cheap way to
//! regenerate both from a tree that is already on disk.

use std::collections::{BTreeMap, HashSet};
use std::path::Path;
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

use anyhow::{Context, Result};
use serde_json::{json, Map, Value};

use crate::meta::{ensure_ascii, Meta};

/// What the run itself, as opposed to the tree, has to say.
pub struct Summary<'a> {
    pub out: &'a Path,
    pub anchors: &'a [u64],
    pub anchor_set: &'a HashSet<u64>,
    pub walked: usize,
    pub depth: i64,
    pub max_functions: usize,
    pub today: &'a str,
}

pub fn write_tree(real: &BTreeMap<u64, Meta>, s: &Summary) -> Result<()> {
    write_index(real, s)?;
    write_graph(real, s)?;
    write_readme(real.len(), s)
}

fn write_index(real: &BTreeMap<u64, Meta>, s: &Summary) -> Result<()> {
    let mut rows = vec!["address\tname\tdepth\tcallers\tcallees\tanchor".to_string()];
    for (va, m) in real {
        rows.push(format!(
            "{va:x}\t{}\t{}\t{}{}\t{}\t{}",
            m.name,
            // A file whose metadata line has no depth prints the literal
            // `None`, which is what Python's `str(m.get("depth", ""))` did with
            // the key `meta_in` always creates. See the port notes: only a
            // hand-edited line can produce it.
            m.depth.map_or_else(|| "None".to_string(), |d| d.to_string()),
            m.callers.len(),
            if m.callers_truncated { "+" } else { "" },
            m.callees.len(),
            if s.anchor_set.contains(va) { "yes" } else { "" }
        ));
    }
    let path = s.out.join("index.tsv");
    std::fs::write(&path, rows.join("\n") + "\n")
        .with_context(|| format!("writing {}", path.display()))
}

fn write_graph(real: &BTreeMap<u64, Meta>, s: &Summary) -> Result<()> {
    let mut nodes = Map::new();
    for (va, m) in real {
        nodes.insert(format!("{va:x}"), Value::String(m.name.clone()));
    }
    // Sorted as pairs of hex strings, not of numbers, because that is what the
    // Python sorted. Every in-module address is nine hex digits, so the two
    // orders agree; the set is what matters, the ordering only has to be
    // stable so two exports of the same build diff clean.
    let mut edges: Vec<(String, String)> = real
        .iter()
        .flat_map(|(va, m)| m.callees.iter().map(move |c| (format!("{va:x}"), format!("{c:x}"))))
        .collect();
    edges.sort();
    edges.dedup();
    let doc = json!({
        "build": desert_tools::paths::build_id().unwrap_or_else(|| "unknown".to_string()),
        "generated": s.today,
        "anchors": s.anchors.iter().map(|a| format!("{a:x}")).collect::<Vec<_>>(),
        "nodes": Value::Object(nodes),
        "calls": edges.iter().map(|(a, b)| json!([a, b])).collect::<Vec<_>>(),
    });
    let path = s.out.join("graph.json");
    std::fs::write(&path, pretty(&doc)? + "\n").with_context(|| format!("writing {}", path.display()))
}

/// `json.dumps(indent=1)`: one space per level, `": "` after a key.
fn pretty(v: &Value) -> Result<String> {
    let mut buf = Vec::new();
    let fmt = serde_json::ser::PrettyFormatter::with_indent(b" ");
    let mut ser = serde_json::Serializer::with_formatter(&mut buf, fmt);
    serde::Serialize::serialize(v, &mut ser).context("serialising graph.json")?;
    Ok(ensure_ascii(&String::from_utf8(buf).context("graph.json is not UTF-8")?))
}

fn write_readme(total: usize, s: &Summary) -> Result<()> {
    let build = desert_tools::paths::build_id().unwrap_or_else(|| "unknown".to_string());
    let (today, walked, depth, cap) = (s.today, s.walked, s.depth, s.max_functions);
    let anchors = s.anchors.len();
    let text = format!(
        "# evidence/

Generated by `just evidence` on {today} against game
build **{build}**. Not a commit artifact - regenerate it, do not edit it.

- `fn/<address>.md` - one file per function: signature, callers, direct
  callees, decompilation, disassembly.
- `index.tsv` - address, name, depth, caller/callee counts, anchor flag.
- `graph.json` - the call edges, for anything that wants the graph.

{total} function(s) in the tree; this run walked {walked} from
{anchors} anchor(s) at depth {depth}.

Ghidra's project is a fresh auto-analysis, so names are bare `FUN_`. What each
one *means* lives in `docs/reference-internals.md`; this tree is the raw
material that document is written from, and it goes stale on a game update.

Regenerate, and diff against the old tree to find what an update moved:

    just evidence --depth {depth} --max-functions {cap}
"
    );
    let path = s.out.join("README.md");
    std::fs::write(&path, text).with_context(|| format!("writing {}", path.display()))
}

/// Today, in the local timezone, as `%Y-%m-%d`.
///
/// Shelling out to `date` rather than computing it: the Python used
/// `time.strftime`, which is local time, and std has no timezone at all. A UTC
/// calculation would stamp yesterday's date on every tree exported after 5pm
/// in a US timezone, and the date is the first thing anyone compares when
/// asking which of two trees is the newer one. The UTC fallback is for a
/// machine with no `date`, where a stamp that is off by one is still better
/// than no export.
pub fn today() -> String {
    if let Ok(out) = Command::new("date").arg("+%Y-%m-%d").output() {
        if out.status.success() {
            let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
            if s.len() == 10 {
                return s;
            }
        }
    }
    utc_today()
}

fn utc_today() -> String {
    let days = SystemTime::now().duration_since(UNIX_EPOCH).map_or(0, |d| d.as_secs() / 86_400);
    // days-from-civil, inverted (Howard Hinnant's algorithm).
    let z = days as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    format!("{y:04}-{m:02}-{d:02}")
}
