//! Emit: the whole of `crates/desert-core/src/species_table.rs`.
//!
//! The generator owns the whole file - enum, rows, lookup and tests - so it
//! can be regenerated straight over itself. Anything hand-added to the output
//! dies on the next run; add it here instead.

use crate::{Species, SPOT_CHECKS};

/// `s` as a Rust string literal. Character names are printable ASCII (the
/// decoder refuses anything else), so escaping quotes and backslashes is all
/// there is.
fn rust_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

pub struct Counts {
    pub bug: usize,
    pub fish: usize,
    pub critter: usize,
    pub not_hand_catchable: usize,
    pub body: usize,
    pub friendly_body: usize,
}

pub fn species_table_rs(rows: &[Species], counts: &Counts, build: &str) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut push = |s: &str| out.push(s.to_string());
    for l in [
        format!("//! Creature species of Crimson Desert build {build}, by how they are caught."),
        "//!".into(),
        "//! Generated by crates/tools/src/bin/gen-species.rs (`just gen-species`) from".into(),
        "//! the game's own archive tables: characterinfo, interactioninfo and".into(),
        "//! tribeinfo (with knowledgeinfo, iteminfo, npcinfo, mercenaryinfo and".into(),
        "//! vehicleinfo for the per-record layout check). Do not edit by hand; rerun".into(),
        "//! `just gen-species`.".into(),
        "//!".into(),
        "//! The rule. A bag catch is a characterinfo record whose interaction list".into(),
        "//! holds `Insect_Catch` and whose `convertItemInfo` is not 0; it is a `Bug`,".into(),
        "//! `Fish` or `Critter` by the level-2 group of its tribe chain (the insect".into(),
        "//! group, the fish group, any other group). Every other record whose name".into(),
        "//! starts with `Animal_` (any case) is `NotHandCatchable`. Every record".into(),
        "//! not named `Animal_*` whose interaction list holds `Dead_Loot` is a".into(),
        "//! `FriendlyBody` when its `isEnableFriendly` flag is 1 and a `Body` when".into(),
        "//! it is 0. Any other name is absent.".into(),
        "".into(),
        "/// How a creature species is caught.".into(),
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]".into(),
        "pub enum SpeciesClass {".into(),
        "    /// A bag catch in the insect tribe group.".into(),
        "    Bug,".into(),
        "    /// A bag catch in the fish tribe group.".into(),
        "    Fish,".into(),
        "    /// A bag catch in any other tribe group (small animals, birds, ...).".into(),
        "    Critter,".into(),
        "    /// An `Animal_*` record that is not a bag catch: carried, skinned,".into(),
        "    /// ridden, or not caught at all.".into(),
        "    NotHandCatchable,".into(),
        "    /// A hostile person or monster (not `Animal_*`, `isEnableFriendly`".into(),
        "    /// 0: bandits, criminals, monsters) whose corpse is searched".into(),
        "    /// (`Dead_Loot`): never a catch.".into(),
        "    Body,".into(),
        "    /// A person who was not an enemy (`isEnableFriendly` 1: citizens,".into(),
        "    /// traders, mercenaries) whose corpse is searched: never a catch.".into(),
        "    FriendlyBody,".into(),
        "}".into(),
        "".into(),
        "/// Every classified species as `(characterinfo record name, class)`, sorted".into(),
        "/// by name in byte order so [`species_class`] can binary-search it.".into(),
        "pub const SPECIES: &[(&str, SpeciesClass)] = &[".into(),
    ] {
        push(&l);
    }
    for r in rows {
        push(&format!("    ({}, SpeciesClass::{}),", rust_str(&r.name), r.class.variant()));
    }
    for l in [
        "];".to_string(),
        "".into(),
        "/// The class of the characterinfo record named `name`, `None` when it is".into(),
        "/// neither a bag catch, an `Animal_*` record nor a searchable body.".into(),
        "pub fn species_class(name: &str) -> Option<SpeciesClass> {".into(),
        "    SPECIES".into(),
        "        .binary_search_by(|(n, _)| n.cmp(&name))".into(),
        "        .ok()".into(),
        "        .and_then(|i| SPECIES.get(i))".into(),
        "        .map(|&(_, c)| c)".into(),
        "}".into(),
        "".into(),
        "#[cfg(test)]".into(),
        "mod tests {".into(),
        "    use super::*;".into(),
        "".into(),
        "    #[test]".into(),
        "    fn sorted_and_unique() {".into(),
        "        assert!(SPECIES.windows(2).all(|w| w[0].0 < w[1].0));".into(),
        "    }".into(),
        "".into(),
        "    fn count(c: SpeciesClass) -> usize {".into(),
        "        SPECIES.iter().filter(|(_, x)| *x == c).count()".into(),
        "    }".into(),
        "".into(),
        format!("    /// The counts on build {build}."),
        "    #[test]".into(),
        "    fn pinned_counts() {".into(),
        format!("        assert_eq!(count(SpeciesClass::Bug), {});", counts.bug),
        format!("        assert_eq!(count(SpeciesClass::Fish), {});", counts.fish),
        format!("        assert_eq!(count(SpeciesClass::Critter), {});", counts.critter),
        format!("        assert_eq!(count(SpeciesClass::NotHandCatchable), {});", counts.not_hand_catchable),
        format!("        assert_eq!(count(SpeciesClass::Body), {});", counts.body),
        format!("        assert_eq!(count(SpeciesClass::FriendlyBody), {});", counts.friendly_body),
        "    }".into(),
        "".into(),
        "    #[test]".into(),
        "    fn spot_checks() {".into(),
    ] {
        push(&l);
    }
    for (name, want) in SPOT_CHECKS {
        let want = match want {
            Some(c) => format!("Some(SpeciesClass::{})", c.variant()),
            None => "None".to_string(),
        };
        push(&format!("        assert_eq!(species_class({}), {want});", rust_str(name)));
    }
    push("    }");
    push("}");
    let mut text = out.join("\n");
    text.push('\n');
    text
}

/// The rows of a `species_table.rs` already on disk, `name -> variant`.
pub fn previous_rows(text: &str) -> std::collections::BTreeMap<String, String> {
    let mut out = std::collections::BTreeMap::new();
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix("(\"") else { continue };
        let Some((name, tail)) = rest.split_once("\", SpeciesClass::") else { continue };
        let Some(variant) = tail.strip_suffix("),") else { continue };
        out.insert(name.replace("\\\"", "\"").replace("\\\\", "\\"), variant.to_string());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Class;

    #[test]
    fn previous_rows_read_back_what_is_written() {
        let rows = vec![
            Species { name: "Animal_A".into(), class: Class::Bug, group: None, convert_item: 1 },
            Species { name: "Animal_B".into(), class: Class::NotHandCatchable, group: None, convert_item: 0 },
        ];
        let text = species_table_rs(&rows, &Counts { bug: 1, fish: 0, critter: 0, not_hand_catchable: 1, body: 0, friendly_body: 0 }, "1");
        let got = previous_rows(&text);
        assert_eq!(got.len(), 2);
        assert_eq!(got["Animal_A"], "Bug");
        assert_eq!(got["Animal_B"], "NotHandCatchable");
    }
}
