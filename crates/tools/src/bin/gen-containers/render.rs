//! Emit: the whole of `crates/desert-core/src/container_table.rs`.
//!
//! The generator owns the whole file - enum, rows, lookup and tests - so it
//! can be regenerated straight over itself. Anything hand-added to the output
//! dies on the next run; add it here instead.

use crate::{Container, SPOT_CHECKS};

pub struct Counts {
    pub item_container: usize,
    pub furniture_drop: usize,
}

pub fn container_table_rs(rows: &[Container], counts: &Counts, build: &str) -> String {
    let mut out: Vec<String> = Vec::new();
    for l in [
        format!("//! The take-able containers of Crimson Desert build {build}, by gimmick key."),
        "//!".into(),
        "//! Generated by crates/tools/src/bin/gen-containers.rs (`just gen-containers`)".into(),
        "//! from the game's own archive tables: gimmickinfo (each record walked from".into(),
        "//! its key through its tags) and interactioninfo (`checkLootableField`). Do".into(),
        "//! not edit by hand; rerun `just gen-containers`.".into(),
        "//!".into(),
        "//! The rule, `analysis/container_catalog.py`'s for these two classes: a".into(),
        "//! record with a take interaction (`checkLootableField` 1 and named".into(),
        "//! `Gimmick_PickUp*`, `ItemHot_Collect*`, `ItemCold_Collect*`,".into(),
        "//! `Item_Collect_Reward*`, `Ship_PickUp*` or `ReadMemory_Paper_Collect*`)".into(),
        "//! that is not a puzzle box, a puzzle-box part, a chest, furniture storage".into(),
        "//! or personal storage is a `FurnitureDrop` when it carries the tag".into(),
        "//! `furniture_drop` and an `ItemContainer` when it carries".into(),
        "//! `catch_itemcontainer`. Every other record is absent: chests, breakable".into(),
        "//! containers, furniture doors and the player's own storage are not here.".into(),
        "".into(),
        "/// What kind of take-able container a gimmick record is.".into(),
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]".into(),
        "pub enum ContainerClass {".into(),
        "    /// A self-contained basket, sack, crate, potion or donation box".into(),
        "    /// (`catch_itemcontainer`), taken whole; its own drop list is the".into(),
        "    /// contents.".into(),
        "    ItemContainer,".into(),
        "    /// A take-able box or bundle furniture hands out (`furniture_drop`),".into(),
        "    /// whose drop list is a room table.".into(),
        "    FurnitureDrop,".into(),
        "}".into(),
        "".into(),
        "impl ContainerClass {".into(),
        "    /// The word the log lines use.".into(),
        "    pub fn name(self) -> &'static str {".into(),
        "        match self {".into(),
        "            ContainerClass::ItemContainer => \"item-container\",".into(),
        "            ContainerClass::FurnitureDrop => \"furniture-drop\",".into(),
        "        }".into(),
        "    }".into(),
        "}".into(),
        "".into(),
        "/// Every take-able container as `(gimmickinfo key, class)`, sorted by key".into(),
        "/// so [`container_class`] can binary-search it. The record name is in the".into(),
        "/// comment.".into(),
        "pub const CONTAINERS: &[(u32, ContainerClass)] = &[".into(),
    ] {
        out.push(l);
    }
    for r in rows {
        out.push(format!("    ({}, ContainerClass::{}), // {}", r.key, r.class.variant(), r.name));
    }
    for l in [
        "];".to_string(),
        "".into(),
        "/// The class of the gimmickinfo record keyed `key`, `None` when it is not a".into(),
        "/// take-able container.".into(),
        "pub fn container_class(key: u32) -> Option<ContainerClass> {".into(),
        "    CONTAINERS".into(),
        "        .binary_search_by(|(k, _)| k.cmp(&key))".into(),
        "        .ok()".into(),
        "        .and_then(|i| CONTAINERS.get(i))".into(),
        "        .map(|&(_, c)| c)".into(),
        "}".into(),
        "".into(),
        "#[cfg(test)]".into(),
        "mod tests {".into(),
        "    use super::*;".into(),
        "".into(),
        "    #[test]".into(),
        "    fn sorted_and_unique() {".into(),
        "        assert!(CONTAINERS.windows(2).all(|w| w[0].0 < w[1].0));".into(),
        "    }".into(),
        "".into(),
        "    fn count(c: ContainerClass) -> usize {".into(),
        "        CONTAINERS.iter().filter(|(_, x)| *x == c).count()".into(),
        "    }".into(),
        "".into(),
        format!("    /// The counts on build {build}."),
        "    #[test]".into(),
        "    fn pinned_counts() {".into(),
        format!("        assert_eq!(count(ContainerClass::ItemContainer), {});", counts.item_container),
        format!("        assert_eq!(count(ContainerClass::FurnitureDrop), {});", counts.furniture_drop),
        "    }".into(),
        "".into(),
        "    #[test]".into(),
        "    fn spot_checks() {".into(),
    ] {
        out.push(l);
    }
    for (key, name, want) in SPOT_CHECKS {
        let want = match want {
            Some(c) => format!("Some(ContainerClass::{})", c.variant()),
            None => "None".to_string(),
        };
        out.push(format!("        assert_eq!(container_class({key}), {want}); // {name}"));
    }
    for l in [
        "        assert_eq!(container_class(0), None);",
        "        assert_eq!(container_class(u32::MAX), None);",
        "    }",
        "",
        "    #[test]",
        "    fn names_are_the_log_vocabulary() {",
        "        assert_eq!(ContainerClass::ItemContainer.name(), \"item-container\");",
        "        assert_eq!(ContainerClass::FurnitureDrop.name(), \"furniture-drop\");",
        "    }",
        "}",
    ] {
        out.push(l.to_string());
    }
    let mut text = out.join("\n");
    text.push('\n');
    text
}

/// The rows of a `container_table.rs` already on disk, `key -> variant`.
pub fn previous_rows(text: &str) -> std::collections::BTreeMap<u32, String> {
    let mut out = std::collections::BTreeMap::new();
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix('(') else { continue };
        let Some((key, tail)) = rest.split_once(", ContainerClass::") else { continue };
        let Some((variant, _)) = tail.split_once("),") else { continue };
        if let Ok(k) = key.parse::<u32>() {
            out.insert(k, variant.to_string());
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Class;

    #[test]
    fn previous_rows_read_back_what_is_written() {
        let rows = vec![
            Container { key: 7, name: "basket".into(), class: Class::ItemContainer },
            Container { key: 9, name: "cabinet".into(), class: Class::FurnitureDrop },
        ];
        let text = container_table_rs(&rows, &Counts { item_container: 1, furniture_drop: 1 }, "1");
        let got = previous_rows(&text);
        assert_eq!(got.len(), 2);
        assert_eq!(got[&7], "ItemContainer");
        assert_eq!(got[&9], "FurnitureDrop");
    }
}
