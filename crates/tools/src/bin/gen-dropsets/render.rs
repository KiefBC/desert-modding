//! Emit: the whole of `crates/desert-core/src/dropset_table.rs`.
//!
//! The generator owns the whole file - enum, struct, rows, lookup and tests -
//! so it can be regenerated straight over itself. Anything hand-added to the
//! output dies on the next run; add it here instead.

use std::collections::{BTreeMap, HashMap};

use crate::{Group, Row, SPOT_CHECKS};

pub struct Counts {
    pub pouch: usize,
    pub breakable: usize,
    pub refused_pouch: usize,
    pub refused_breakable: usize,
    pub pouch_candidates: usize,
    pub breakable_candidates: usize,
    pub pouch_items: usize,
    pub breakable_gimmicks: usize,
}

pub fn dropset_table_rs(
    rows: &[Row],
    refused: &[(u32, Group, String)],
    names: &HashMap<u32, String>,
    c: &Counts,
    build: &str,
) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut push = |l: String| out.push(l);
    for l in [
        "//! The `dropsetinfo` rows the `[Harvest]` `Pouches` and `Breakables` levers".into(),
        format!("//! multiply, by dropset key, on Crimson Desert build {build}."),
        "//!".into(),
        "//! Generated by crates/tools/src/bin/gen-dropsets.rs (`just gen-dropsets`) from".into(),
        "//! the game's own archive tables, every record walked to its last byte:".into(),
        "//! dropsetinfo, gimmickinfo, interactioninfo, breakableobjectinfo,".into(),
        "//! itemuseinfo, iteminfo, multichangeinfo, missioninfo and factionnode. Do".into(),
        "//! not edit by hand; rerun `just gen-dropsets`.".into(),
        "//!".into(),
        format!(
            "//! - `Pouch`: {} rows. The dropset of an `itemuseinfo` RandomBox record",
            c.pouch
        ),
        "//!   (kind 2) an item's `_itemUseInfoList` names: what an item pays when it".into(),
        format!(
            "//!   is opened ({} items, {} rows before refusals). The five coin pouches,",
            c.pouch_items, c.pouch_candidates
        ),
        "//!   and the seed packs, chest items, recipe and gear boxes that open the".into(),
        "//!   same way.".into(),
        format!(
            "//! - `Breakable`: {} rows. The `dropSetInfoList` of the {} gimmick records the",
            c.breakable, c.breakable_gimmicks
        ),
        format!(
            "//!   container catalogue calls \"Breakable container\" ({} rows before refusals):",
            c.breakable_candidates
        ),
        "//!   breakable, a loot list, no loot interaction; barrels, crates, pots, sacks.".into(),
        "//!".into(),
        format!(
            "//! **Refused: {} pouch and {} breakable rows**, each listed in [`REFUSED`] with why.",
            c.refused_pouch, c.refused_breakable
        ),
        "//! A row another source also pays from (another gimmick class, an interaction".into(),
        "//! or override, a gimmick's productData, crafting, a quest or mission, a".into(),
        "//! dispatch operation, faction research, a religion block cost, or the other".into(),
        "//! group) is refused because multiplying it would multiply that source too; a".into(),
        "//! row with no item entry (knowledge, mounts, pets) has nothing to multiply. The".into(),
        "//! sources the generator does not walk - the character tables' loot and pockets,".into(),
        "//! quest dialogue, stage, sub-level and mini-game rewards - were checked against".into(),
        "//! the catalogue database (`analysis/catalog_db.py`, view `item_source`) on".into(),
        "//! 26361232 and shared none of these rows; repeat that query after an update.".into(),
        "//!".into(),
        "//! Each row carries what the plugin checks the parsed row against before it".into(),
        "//! writes: the record index the manager files it under (the archive header's".into(),
        "//! order), the declared entry count, and `sum(min + max)` over its item".into(),
        "//! entries (kind 0), the only entries either lever multiplies.".into(),
        "".into(),
        "/// Which lever a row belongs to.".into(),
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]".into(),
        "pub enum RowGroup {".into(),
        "    /// What an item pays when it is opened: `[Harvest] Pouches`.".into(),
        "    Pouch,".into(),
        "    /// What a barrel, crate, pot or sack pays when it is smashed:".into(),
        "    /// `[Harvest] Breakables`.".into(),
        "    Breakable,".into(),
        "}".into(),
        "".into(),
        "impl RowGroup {".into(),
        "    /// The word the log lines use.".into(),
        "    pub fn name(self) -> &'static str {".into(),
        "        match self {".into(),
        "            RowGroup::Pouch => \"pouch\",".into(),
        "            RowGroup::Breakable => \"breakable\",".into(),
        "        }".into(),
        "    }".into(),
        "}".into(),
        "".into(),
        "/// One row.".into(),
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]".into(),
        "pub struct DropsetRow {".into(),
        "    /// The `dropsetinfo` key.".into(),
        "    pub key: u32,".into(),
        "    /// The record index: the row's position in the archive header, which is".into(),
        "    /// the manager's `+0x58` slot the parsed row is filed under.".into(),
        "    pub index: u16,".into(),
        "    pub group: RowGroup,".into(),
        "    /// The declared entry count, the parsed row's `+0x28`.".into(),
        "    pub entries: u16,".into(),
        "    /// `sum(min + max)` over the item (kind 0) entries, vanilla.".into(),
        "    pub item_amounts: i64,".into(),
        "}".into(),
        "".into(),
        "/// The game build these rows were generated on.".into(),
        format!("pub const BUILD: &str = \"{build}\";"),
        "".into(),
        "/// Every row, sorted by key so [`lookup`] can binary-search it. The row name".into(),
        "/// is in the comment.".into(),
        "pub const ROWS: &[DropsetRow] = &[".into(),
    ] {
        push(l);
    }
    for r in rows {
        push(format!(
            "    DropsetRow {{ key: {}, index: {}, group: RowGroup::{}, entries: {}, item_amounts: {} }}, // {}",
            r.key,
            r.index,
            r.group.variant(),
            r.entries,
            r.amounts,
            r.name
        ));
    }
    for l in [
        "];",
        "",
        "/// The row keyed `key`, `None` when neither lever touches it.",
        "pub fn lookup(key: u32) -> Option<&'static DropsetRow> {",
        "    ROWS.binary_search_by(|r| r.key.cmp(&key)).ok().and_then(|i| ROWS.get(i))",
        "}",
        "",
        "/// The rows the generator refused, `(key, the group it would have joined,",
        "/// why)`: every one is paid from by another source as well.",
        "pub const REFUSED: &[(u32, RowGroup, &str)] = &[",
    ] {
        push(l.to_string());
    }
    for (k, g, why) in refused {
        let name = names.get(k).map(String::as_str).unwrap_or("?");
        push(format!("    ({k}, RowGroup::{}, \"{}: {}\"),", g.variant(), name, why.replace('"', "'")));
    }
    for l in [
        "];".to_string(),
        "".into(),
        "#[cfg(test)]".into(),
        "mod tests {".into(),
        "    use super::*;".into(),
        "".into(),
        "    #[test]".into(),
        "    fn sorted_and_unique() {".into(),
        "        assert!(ROWS.windows(2).all(|w| w[0].key < w[1].key));".into(),
        "        let mut idx: Vec<u16> = ROWS.iter().map(|r| r.index).collect();".into(),
        "        idx.sort_unstable();".into(),
        "        idx.dedup();".into(),
        "        assert_eq!(idx.len(), ROWS.len(), \"two rows under one record index\");".into(),
        "    }".into(),
        "".into(),
        "    fn count(g: RowGroup) -> usize {".into(),
        "        ROWS.iter().filter(|r| r.group == g).count()".into(),
        "    }".into(),
        "".into(),
        format!("    /// The counts on build {build}."),
        "    #[test]".into(),
        "    fn pinned_counts() {".into(),
        format!("        assert_eq!(count(RowGroup::Pouch), {});", c.pouch),
        format!("        assert_eq!(count(RowGroup::Breakable), {});", c.breakable),
        format!("        assert_eq!(REFUSED.len(), {});", c.refused_pouch + c.refused_breakable),
        "    }".into(),
        "".into(),
        "    /// A key is in one group at most, and a refused key in none.".into(),
        "    #[test]".into(),
        "    fn no_key_in_two_groups_and_refused_keys_absent() {".into(),
        "        for (k, _, _) in REFUSED {".into(),
        "            assert_eq!(lookup(*k), None, \"refused row {k} is in the table\");".into(),
        "        }".into(),
        "        // `sorted_and_unique` makes a key's group single-valued; this says it".into(),
        "        // in the words of the rule.".into(),
        "        for r in ROWS {".into(),
        "            assert_eq!(ROWS.iter().filter(|x| x.key == r.key).count(), 1);".into(),
        "        }".into(),
        "    }".into(),
        "".into(),
        "    /// Every row has something to multiply and an entry count the dispatch".into(),
        "    /// write path accepts.".into(),
        "    #[test]".into(),
        "    fn rows_are_plausible() {".into(),
        "        for r in ROWS {".into(),
        "            assert!(r.item_amounts >= 2, \"{r:?}\");".into(),
        "            assert!((1..=64).contains(&r.entries), \"{r:?}\");".into(),
        "        }".into(),
        "    }".into(),
        "".into(),
        "    #[test]".into(),
        "    fn spot_checks() {".into(),
    ] {
        push(l);
    }
    for (key, name, want) in SPOT_CHECKS {
        let want = match want {
            Some(g) => format!("Some(RowGroup::{})", g.variant()),
            None => "None".to_string(),
        };
        push(format!("        assert_eq!(lookup({key}).map(|r| r.group), {want}); // {name}"));
    }
    for l in [
        "        assert_eq!(lookup(0), None);",
        "        assert_eq!(lookup(u32::MAX), None);",
        "    }",
        "",
        "    #[test]",
        "    fn names_are_the_log_vocabulary() {",
        "        assert_eq!(RowGroup::Pouch.name(), \"pouch\");",
        "        assert_eq!(RowGroup::Breakable.name(), \"breakable\");",
        "    }",
        "}",
    ] {
        push(l.to_string());
    }
    let mut text = out.join("\n");
    text.push('\n');
    text
}

/// The rows of a `dropset_table.rs` already on disk, `key -> variant`.
pub fn previous_rows(text: &str) -> BTreeMap<u32, String> {
    let mut out = BTreeMap::new();
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix("DropsetRow { key: ") else { continue };
        let Some((key, tail)) = rest.split_once(',') else { continue };
        let Some((_, tail)) = tail.split_once("group: RowGroup::") else { continue };
        let Some((variant, _)) = tail.split_once(',') else { continue };
        if let Ok(k) = key.parse::<u32>() {
            out.insert(k, variant.to_string());
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn previous_rows_read_back_what_is_written() {
        let rows = vec![
            Row { key: 7, index: 1, name: "a".into(), group: Group::Pouch, entries: 1, items: 1, amounts: 2 },
            Row { key: 9, index: 2, name: "b".into(), group: Group::Breakable, entries: 2, items: 1, amounts: 3 },
        ];
        let c = Counts {
            pouch: 1,
            breakable: 1,
            refused_pouch: 0,
            refused_breakable: 0,
            pouch_candidates: 1,
            breakable_candidates: 1,
            pouch_items: 1,
            breakable_gimmicks: 1,
        };
        let text = dropset_table_rs(&rows, &[], &HashMap::new(), &c, "1");
        let got = previous_rows(&text);
        assert_eq!(got.len(), 2);
        assert_eq!(got[&7], "Pouch");
        assert_eq!(got[&9], "Breakable");
    }
}
